const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { transformSync } = require('@babel/core');

// Load the same pure calculation modules that Metro bundles, without native APIs.
function load(relative) {
  const filename = path.resolve(__dirname, '..', relative);
  const module = { exports: {} };
  const code = transformSync(fs.readFileSync(filename, 'utf8'), { configFile: false, babelrc: false, plugins: ['@babel/plugin-transform-modules-commonjs'] }).code;
  vm.runInNewContext(code, { module, exports: module.exports, require: (name) => load(path.relative(path.resolve(__dirname, '..'), path.resolve(path.dirname(filename), `${name}.js`))) }, { filename });
  return module.exports;
}
